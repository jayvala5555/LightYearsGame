#include "Weapon/Shooter.h"

namespace ly
{

Shooter::Shooter(Actor *owner)
    : mOwner{owner}
{
    
}

//////////////////////////////////////////////////////////////////////

void Shooter::shoot()
{
    if (canShoot() && !isOnCooldown())
    {
        shootImpl();
    }
}

//////////////////////////////////////////////////////////////////////

bool Shooter::canShoot() const
{
    return true;
}

////////////////////////////////////////////////////////////////////

bool Shooter::isOnCooldown() const
{
    return false;
}

//////////////////////////////////////////////////////////////////////

Actor* Shooter::getOwner() const
{
    return mOwner;
}

//////////////////////////////////////////////////////////////////////

} // namespace ly
